/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The transform is intentionally small, explicit and deterministic.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
for (const arg of args) {
  if (arg !== '--check') throw new Error('unknown build-cjs argument: ' + arg);
}
const check = args.includes('--check');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'CODE', 'ZipCageError', 'inspectZipBuffer', 'assertSafeZipBuffer',
  'readZipEntry', 'extractZipBuffer', 'createZipBuffer', 'createZipGuard'
];

let body = source;
for (const name of EXPORT_NAMES) {
  const pattern = new RegExp('^export (?:const|class|function|async function) ' + name + '\\b', 'm');
  if (!pattern.test(body)) throw new Error('CJS transform could not find export ' + name);
}

const imports = [
  [
    "import { createInflateRaw, deflateRawSync } from 'node:zlib';",
    "const { createInflateRaw, deflateRawSync } = require('node:zlib');"
  ],
  [
    "import { randomBytes } from 'node:crypto';",
    "const { randomBytes } = require('node:crypto');"
  ],
  [
    "import { promises as fs } from 'node:fs';",
    "const { promises: fs } = require('node:fs');"
  ],
  [
    "import path from 'node:path';",
    "const path = require('node:path');"
  ],
  [
    "import { Buffer } from 'node:buffer';",
    "const { Buffer } = require('node:buffer');"
  ]
];
for (const [esm, cjs] of imports) {
  if (!body.includes(esm)) throw new Error('CJS transform could not find import: ' + esm);
  body = body.replace(esm, cjs);
}

body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
body = body.replace(/^export async function /gm, 'async function ');

const defaultObjectStart = body.indexOf('const zipcage = Object.freeze({');
if (defaultObjectStart === -1) throw new Error('CJS transform could not find the default export object');
if (!body.trimEnd().endsWith('export default zipcage;')) {
  throw new Error('CJS transform could not find the default export statement');
}
body = body.slice(0, defaultObjectStart).trimEnd();

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body,
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const outputPath = path.join(root, 'cjs', 'index.cjs');
if (check) {
  let current;
  try {
    current = await readFile(outputPath);
  } catch (error) {
    console.error('cjs/index.cjs is missing or unreadable');
    process.exitCode = 1;
  }
  if (process.exitCode !== 1 && !current.equals(Buffer.from(output, 'utf8'))) {
    console.error('cjs/index.cjs is stale; run node scripts/build-cjs.mjs');
    process.exitCode = 1;
  }
  if (process.exitCode !== 1) process.stdout.write('cjs/index.cjs is up to date\n');
} else {
  await mkdir(path.join(root, 'cjs'), { recursive: true });
  await writeFile(outputPath, output, 'utf8');
  process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
}
