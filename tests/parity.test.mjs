import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as esm from '../src/index.mjs';
import esmDefault, {
  CODE,
  inspectZipBuffer,
  createZipBuffer,
  createZipGuard
} from '../src/index.mjs';
import { cjs, validZip, zip } from './helpers.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

test('ESM and CommonJS expose the same public keys', () => {
  assert.deepEqual(Object.keys(cjs).filter((key) => key !== 'default').sort(), Object.keys(esmDefault).sort());
});

test('CommonJS default export is the module object for compatibility', () => {
  assert.equal(cjs.default, cjs);
});

test('ESM default export contains the complete public API', () => {
  for (const key of ['CODE', 'ZipCageError', 'inspectZipBuffer', 'assertSafeZipBuffer', 'readZipEntry', 'extractZipBuffer', 'createZipBuffer', 'createZipGuard']) {
    assert.equal(typeof esmDefault[key], typeof esm[key]);
    assert.equal(esmDefault[key], esm[key]);
  }
});

test('ESM and CommonJS inspect reports are identical for a valid archive', () => {
  const archive = validZip([{ name: 'x.txt', data: 'abc', method: 'deflate' }]);
  assert.deepEqual(cjs.inspectZipBuffer(archive), inspectZipBuffer(archive));
});

test('ESM and CommonJS inspect reports are identical for a hostile archive', () => {
  const archive = zip([{ name: '../x.txt', data: 'abc' }]);
  assert.deepEqual(cjs.inspectZipBuffer(archive), inspectZipBuffer(archive));
});

test('ESM and CommonJS readEntry outputs are identical', async () => {
  const archive = validZip([{ name: 'x.txt', data: 'abc', method: 'deflate' }]);
  const [left, right] = await Promise.all([
    esm.readZipEntry(archive, 'x.txt'),
    cjs.readZipEntry(archive, 'x.txt')
  ]);
  assert.deepEqual(left, right);
  assert.equal(left.toString(), 'abc');
});

test('ESM and CommonJS builders produce byte-identical archives', () => {
  const entries = [
    { name: 'a.txt', data: 'a' },
    { name: 'b.txt', data: 'bbbb', method: 'deflate', dataDescriptor: true }
  ];
  assert.deepEqual(cjs.createZipBuffer(entries), createZipBuffer(entries));
});

test('ESM and CommonJS guards behave identically', async () => {
  const left = createZipGuard({ maxEntries: 2 });
  const right = cjs.createZipGuard({ maxEntries: 2 });
  const archive = validZip([{ name: 'x', data: 'x' }]);
  assert.deepEqual(left.inspect(archive), right.inspect(archive));
  assert.deepEqual(await left.readEntry(archive, 'x'), await right.readEntry(archive, 'x'));
});

test('package self-reference resolves to ESM from import', async () => {
  const self = await import('zipcage');
  assert.equal(self.inspectZipBuffer, inspectZipBuffer);
  assert.equal(self.CODE, CODE);
});

test('package self-reference resolves to CommonJS from require', () => {
  assert.equal(cjs.inspectZipBuffer, cjs.default.inspectZipBuffer);
  assert.equal(typeof cjs.createZipBuffer, 'function');
});

test('generated CommonJS build is byte deterministic', async () => {
  const cjsPath = path.join(root, 'cjs', 'index.cjs');
  const before = await readFile(cjsPath);
  const result = spawnSync(process.execPath, [path.join(root, 'scripts', 'build-cjs.mjs')], {
    cwd: root,
    encoding: 'utf8'
  });
  assert.equal(result.status, 0, result.stderr);
  const after = await readFile(cjsPath);
  assert.deepEqual(after, before);
});

test('generated CommonJS file carries the generator marker', async () => {
  const text = await readFile(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.match(text, /Generated by scripts\/build-cjs\.mjs/);
  assert.match(text, /module\.exports\.default = module\.exports/);
});

test('package manifest declares clean dual-module packaging', async () => {
  const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  assert.equal(pkg.name, 'zipcage');
  assert.equal(pkg.version, '1.0.0');
  assert.equal(pkg.type, 'module');
  assert.equal(pkg.main, './cjs/index.cjs');
  assert.equal(pkg.module, './src/index.mjs');
  assert.equal(pkg.types, './types/index.d.ts');
  assert.equal(pkg.exports['.'].types, './types/index.d.ts');
  assert.equal(pkg.exports['.'].import, './src/index.mjs');
  assert.equal(pkg.exports['.'].require, './cjs/index.cjs');
  assert.deepEqual(pkg.dependencies, {});
  assert.deepEqual(pkg.devDependencies, {});
  assert.equal(pkg.sideEffects, false);
  assert.equal(pkg.engines.node, '>=18');
});

