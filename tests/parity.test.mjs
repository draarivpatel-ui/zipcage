test('gitattributes enforces LF line endings for generated CommonJS', async () => {
  const text = await readFile(path.join(root, '.gitattributes'), 'utf8');
  assert.match(text, /^\* text=auto eol=lf$/m);
  assert.match(text, /^\*\.cjs text eol=lf$/m);
});

test('TypeScript declarations expose the complete public API', async () => {
  const text = await readFile(path.join(root, 'types', 'index.d.ts'), 'utf8');
  for (const fragment of [
    'export const CODE',
    'export declare class ZipCageError',
    'export declare function inspectZipBuffer',
    'export declare function assertSafeZipBuffer',
    'export declare function readZipEntry',
    'export declare function extractZipBuffer',
    'export declare function createZipBuffer',
    'export declare function createZipGuard',
    'export default zipcage'
  ]) {
    assert.ok(text.includes(fragment), 'missing declaration: ' + fragment);
  }
});

test('TypeScript declarations contain every runtime error code', async () => {
  const text = await readFile(path.join(root, 'types', 'index.d.ts'), 'utf8');
  for (const value of Object.values(cjs.CODE)) {
    assert.ok(text.includes(value), 'missing error code ' + value);
  }
});

test('source imports only permitted Node built-ins', async () => {
  const text = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');
  const imports = [...text.matchAll(/^import .*? from '([^']+)';$/gm)].map((match) => match[1]).sort();
  assert.deepEqual(imports, ['node:buffer', 'node:fs', 'node:path', 'node:zlib']);
  assert.equal(/require\s*\(/.test(text), false);
  assert.equal(/import\s*\(/.test(text), false);
});

test('CI covers Node 18, 20, 22 and 24 on Linux and Windows', async () => {
  const ci = await readFile(path.join(root, '.github', 'workflows', 'ci.yml'), 'utf8');
  for (const fragment of ['ubuntu-latest', 'windows-latest', 'node: [18, 20, 22, 24]']) {
    assert.ok(ci.includes(fragment), 'missing CI fragment ' + fragment);
  }
});

test('generated CommonJS has no static ESM export declarations', async () => {
  const text = await readFile(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.equal(/^export\s/m.test(text), false);
  assert.match(text, /^module\.exports = \{$/m);
});
